O = Path("data/server/outputs")
P11 = O / "p11_controlled"
SRW = O / "p12_srw"
WSA, OOF = SRW / "image_dependence", SRW / "image_dependence_oof"
PILOT = Path("reports/results/phase11_label_audit")
R2 = Path("reports/results/phase11_label_audit_r2")

INPUTS = {
    "per_seed": P11 / "caption_vs_xattn_per_seed.csv",
    "cap_stats": P11 / "caption_vs_xattn_stats.json",
    "la_ce": P11 / "paired_analysis.json",
    "wsa_arm": WSA / "arm_condition.csv",
    "wsa_run": WSA / "per_run_condition.csv",
    "oof_arm": OOF / "arm_condition.csv",
    "fig1": WSA / "fig_flip_direction.pdf",
    "tau_screen": SRW / "tau_screen_summary.csv",
    "tau_final": SRW / "tau_final_comparison_test.json",
}
MODELS = [("caption_la", "Caption-only + LA"), ("xattn_ce", "Cross-attn + CE"), ("xattn_la", "Cross-attn + LA")]
ARMS = [("ca_la", "Cross-attn + LA"), ("ca_ce", "Cross-attn + CE")]
CONDS = [("swap_random", "Random swap"), ("swap_same_label", "Same-label swap"), ("swap_diff_label", "Diff-label swap"),
         ("mask_mean", "Mean mask"), ("mask_grey", "Grey mask")]
NUM = {}  # macro name -> formatted string


def f3(x):
    return "--" if x is None or pd.isna(x) else f"{x:.3f}"


def sgn(x):
    if x is None or pd.isna(x):
        return "--"
    return "0.000" if round(x, 3) == 0 else f"{x:+.3f}"


def ci(lo, hi):
    return f"[{sgn(lo)}, {sgn(hi)}]"


def pval(p):
    return "--" if p is None or pd.isna(p) else ("<.001" if p < .001 else f"{p:.3f}".lstrip("0"))


def num(name, value):
    assert name.isalpha(), name
    NUM[name] = value
    return value


def write_table(out, stem, df, tex_body, caption, label):
    df.to_csv(out / "tables" / f"{stem}.csv", index=False)
    tex = ["% generated by scripts/build_srw_tables.py; do not edit", "\\begin{table}[t]", "\\centering", "\\small",
           tex_body, f"\\caption{{{esc(caption)}}}", f"\\label{{{label}}}", "\\end{table}", ""]
    (out / "tables" / f"{stem}.tex").write_text("\n".join(tex))


TEX = {"%": "\\%", "&": "\\&", "_": "\\_", "±": "$\\pm$", "→": "$\\rightarrow$", "Δ": "$\\Delta$",
       "κ": "$\\kappa$", "τ": "$\\tau$", "−": "$-$", "–": "--", "<": "$<$"}


def esc(s):
    s = re.sub(r"(?<![\w.])-(?=\.?\d)", "−", str(s))  # numeric minus -> math minus
    return "".join(TEX.get(ch, ch) for ch in s)


def tabular(df, align):
    rows = ["\\begin{tabular}{" + align + "}", "\\toprule", " & ".join(esc(c) for c in df.columns) + " \\\\", "\\midrule"]
    for r in df.itertuples(index=False):
        if all(str(v) == "" for v in r[1:]):  # panel header
            rows.append(f"\\multicolumn{{{len(df.columns)}}}{{l}}{{\\textit{{{esc(r[0])}}}}} \\\\")
        else:
            rows.append(" & ".join(esc(v) for v in r) + " \\\\")
    rows += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(rows)


# ---------------------------------------------------------------- Table 1
def table1(out):
    ps = pd.read_csv(INPUTS["per_seed"])
    st = json.loads(INPUTS["cap_stats"].read_text())["paired"]
    lc = json.loads(INPUTS["la_ce"].read_text())
    rows = []
    for key, name in MODELS:
        d = ps[ps.model == key]
        assert len(d) == 3, key
        r = {"Model": name}
        for col, lab in (("macro_f1_4", "Macro-F1 (4)"), ("macro_f1_3", "Macro-F1 (3)"), ("accuracy", "Acc."),
                         ("not_f1", "F1 not"), ("image_f1", "F1 image"), ("multi_f1", "F1 multi")):
            m, s = d[col].mean(), d[col].std(ddof=1)
            r[lab] = f"{m:.3f} ± {s:.3f}"
        rows.append(r)
        tag = {"caption_la": "Cap", "xattn_ce": "CE", "xattn_la": "LA"}[key]
        num(f"mfFour{tag}", f"{d.macro_f1_4.mean():.3f}")
        num(f"mfFour{tag}SD", f"{d.macro_f1_4.std(ddof=1):.3f}")
        num(f"mfThree{tag}", f"{d.macro_f1_3.mean():.3f}")
        num(f"acc{tag}", f"{d.accuracy.mean():.3f}")
        num(f"textFOne{tag}", f"{d.text_f1.max():.3f}")
    main = pd.DataFrame(rows)

    diffs = []
    for k, lab, tag in (("xattn_la - caption_la | macro_f1_4", "Cross-attn + LA − caption-only", "LAvCap"),
                        ("xattn_ce - caption_la | macro_f1_4", "Cross-attn + CE − caption-only", "CEvCap")):
        v = st[k]
        diffs.append({"Paired difference (macro-F1, 4)": lab, "Mean": sgn(v["mean"]), "95% CI": ci(*v["ci95"]),
                      "Per seed (42 / 1 / 2)": " / ".join(sgn(v["per_seed"][s]) for s in ("42", "1", "2"))})
        num(f"diff{tag}", sgn(v["mean"])), num(f"diff{tag}CI", ci(*v["ci95"]))
    diffs.append({"Paired difference (macro-F1, 4)": "Cross-attn + LA − cross-attn + CE", "Mean": sgn(lc["mean_diff_macro_f1_4"]),
                  "95% CI": ci(*lc["paired_bootstrap_95ci"]),
                  "Per seed (42 / 1 / 2)": " / ".join(sgn(lc["per_seed_diff_macro_f1_4"][s]) for s in ("42", "1", "2"))})
    num("diffLAvCE", sgn(lc["mean_diff_macro_f1_4"])), num("diffLAvCECI", ci(*lc["paired_bootstrap_95ci"]))
    num("diffLAvCEGroupCI", ci(*lc["group_bootstrap_95ci"]))
    diffs = pd.DataFrame(diffs)

    body = tabular(main, "l" + "c" * (len(main.columns) - 1)) + "\n\\vspace{4pt}\n" + tabular(diffs, "lccc")
    diffs.to_csv(out / "tables" / "table1_controlled_paired.csv", index=False)
    write_table(out, "table1_controlled", main, body,
                "Private test (n = 1,504), mean ± SD over seeds 42/1/2. Checkpoints selected on the public test. "
                "F1 text is 0 for every run (n = 7). Paired differences: bootstrap over test ids (B = 10,000), "
                "seed-averaged.", "tab:controlled")


# ---------------------------------------------------------------- Table 2
def table2(out):
    arm = pd.read_csv(INPUTS["wsa_arm"])
    run = pd.read_csv(INPUTS["wsa_run"])
    oof = pd.read_csv(INPUTS["oof_arm"])
    pt = arm[arm.set == "private_test"]
    cap = pt[pt.arm == "p11_caption_la"]
    assert (cap.flip_rate == 0).all(), "caption-only control must not flip"
    num("capFlipMax", f"{cap.flip_rate.max():.3f}")
    rows = []
    for a, aname in ARMS:
        rows.append({"Condition": aname, **{c: "" for c in ("Flip rate [95% CI]", "Seed range", "Δp(gold)", "Macro-F1 orig → cond", "OOF train flip")}})
        for fam, fname in CONDS:
            r = pt[(pt.arm == a) & (pt.family == fam)].iloc[0]
            seeds = (run[(run.arm == a) & (run.family == fam) & (run.set == "private_test")]
                     .groupby("seed").flip_rate.mean())
            o = oof[(oof.family == fam)]
            tag = f"{'LA' if a == 'ca_la' else 'CE'}{''.join(w.title() for w in fam.split('_'))}"
            rows.append({"Condition": fname,
                         "Flip rate [95% CI]": f"{r.flip_rate:.3f} [{r.flip_ci_lo:.3f}, {r.flip_ci_hi:.3f}]",
                         "Seed range": f"{seeds.min():.3f}–{seeds.max():.3f}",
                         "Δp(gold)": sgn(r.mean_d_p_gold),
                         "Macro-F1 orig → cond": f"{r.macro_f1_4_orig:.3f} → {r.macro_f1_4_cond:.3f}",
                         "OOF train flip": f"{o.flip_rate.iloc[0]:.3f}" if a == "ca_la" and len(o) else "--"})
            num(f"flip{tag}", f"{r.flip_rate:.3f}"), num(f"flip{tag}CI", f"[{r.flip_ci_lo:.3f}, {r.flip_ci_hi:.3f}]")
            num(f"flip{tag}SeedMin", f"{seeds.min():.3f}"), num(f"flip{tag}SeedMax", f"{seeds.max():.3f}")
            num(f"dpGold{tag}", sgn(r.mean_d_p_gold))
            num(f"mfOrig{tag}", f"{r.macro_f1_4_orig:.3f}"), num(f"mfCond{tag}", f"{r.macro_f1_4_cond:.3f}")
            num(f"predSarcOrig{tag}", f"{r.pred_sarcastic_orig:.0f}"), num(f"predSarcCond{tag}", f"{r.pred_sarcastic_cond:.0f}")
            if a == "ca_la" and len(o):
                num(f"oofFlip{''.join(w.title() for w in fam.split('_'))}", f"{o.flip_rate.iloc[0]:.3f}")
    num("oofN", f"{int(oof.n.iloc[0]):,}")
    df = pd.DataFrame(rows)
    write_table(out, "table2_image_dependence", df, tabular(df, "lccccc"),
                "Image dependence on the private test (n = 1,504). The caption is fixed; only the CLIP image output "
                "is replaced. Flip rate and Δp(gold) are averaged over 3 model seeds and the condition draws (5 per "
                "swap); CIs bootstrap test ids (B = 10,000) and exclude seed variance, shown separately as the range "
                "of per-seed flip rates. Caption-only + LA: 0 flips under every condition. OOF train: τ = 1.0 fold "
                "models, held-out folds of train (n = 10,805), seed 42.", "tab:image-dependence")


