"""WS-D: build every table, figure and in-text number for the EACL SRW paper from frozen outputs (run plan §5).

    python scripts/build_srw_tables.py [--out reports/paper_srw] [--n-perm 10000]

No training or inference. Reads only:
  p11_controlled/{caption_vs_xattn_per_seed.csv, caption_vs_xattn_stats.json, paired_analysis.json}
  p12_srw/image_dependence{,_oof}/{arm_condition.csv, per_run_condition.csv}, fig_flip_direction.pdf
  p12_srw/{tau_screen_summary.csv, tau_final_comparison_test.json}
  reports/results/phase11_label_audit/ (pilot sheets) and phase11_label_audit_r2/analysis/round2_analysis.json (if present)
The pilot audit is re-analysed with scripts/analyze_audit_round2.py (same code as round 2), via a pilot view in
a pilot view. Round-2 cells say "pending" until that analysis exists.

The pilot view is written to p12_srw/paper_build/pilot_as_r2/ (it holds gold labels; not a paper file).

Writes to <out>:
  tables/table{1_controlled,2_image_dependence,3_audit,A1_tau}.{tex,csv} (+ table1_controlled_paired.csv)
  figures/fig_flip_direction.pdf
  numbers.tex (\\newcommand macros for every number quoted in the text) and numbers.json
  MANIFEST.json (sha256 of every input, git commit, time)
Every number in the paper must come from these files. No hand-typed numbers.
"""
