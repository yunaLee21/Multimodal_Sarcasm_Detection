def pilot_view(out):
    """Materialise the pilot in round-2 layout and run the round-2 analysis on it."""
    v = SRW / "paper_build" / "pilot_as_r2"
    if v.exists():
        shutil.rmtree(v)
    (v / "batch1").mkdir(parents=True)
    k = pd.read_csv(PILOT / "coordinator_key.csv", dtype=str, encoding="utf-8-sig")
    k["half"], k["stratum"], k["weight"] = "stratified", "strat_" + k.original_label.str.split("-").str[0], 1.0
    k.to_csv(v / "coordinator_key.csv", index=False, encoding="utf-8-sig")
    for f in PILOT.glob("0[123]_*_*.csv"):
        shutil.copyfile(f, v / "batch1" / f.name)
    return v


def run_analysis(d, n_perm):
    subprocess.run([sys.executable, "scripts/analyze_audit_round2.py", "--dir", str(d), "--n-perm", str(n_perm)],
                   check=True, stdout=subprocess.DEVNULL)
    return json.loads((d / "analysis" / "round2_analysis.json").read_text())


def table3(out, n_perm):
    pilot = run_analysis(pilot_view(out), n_perm)
    r2_path = R2 / "analysis" / "round2_analysis.json"
    r2 = json.loads(r2_path.read_text()) if r2_path.exists() else {}
    if r2:
        INPUTS["round2"] = r2_path
    rows = [{"": "Agreement (2 humans)", "Pilot n": "", "Pilot raw": "", "Pilot κ": "", "Round 2 n": "", "Round 2 raw (w)": "", "Round 2 κ (w)": ""}]
    for part, lab in (("caption", "Caption alone"), ("image", "Image alone"), ("pair", "Pair"),
                      ("image_role_given_both_pair_co", "Image role | pair sarcastic")):
        p = pilot["reliability_batch1"][part]
        q = r2.get("reliability_batch1", {}).get(part)
        rows.append({"": lab, "Pilot n": p["n"], "Pilot raw": f3(p["raw_agreement"]), "Pilot κ": f3(p["kappa"]),
                     "Round 2 n": q["n"] if q else "pending",
                     "Round 2 raw (w)": f3(q.get("raw_agreement_weighted", q["raw_agreement"])) if q else "pending",
                     "Round 2 κ (w)": f3(q.get("kappa_weighted", q["kappa"])) if q else "pending"})
        tag = "".join(w.title() for w in part.split("_")[:2])
        num(f"pilotKappa{tag}", f3(p["kappa"])), num(f"pilotRaw{tag}", f3(p["raw_agreement"]))
        if q:
            num(f"rTwoKappa{tag}", f3(q.get("kappa_weighted", q["kappa"])))
    rows.append({"": "Gate A: flip rate, image-needed vs other (both humans)", **{c: "" for c in list(rows[0])[1:]}})
    for arm, cond, lab in (("xattn_la", "random_swap", "LA, random swap"), ("xattn_ce", "random_swap", "CE, random swap"),
                           ("xattn_la", "mean_mask", "LA, mean mask"), ("xattn_ce", "mean_mask", "CE, mean mask")):
        cells = {}
        for src, res, pre in (("Pilot", pilot, "p"), ("Round 2", r2, "r")):
            s = res.get("gate_a", {}).get("sets", {}).get("needed_both_humans")
            t = next((t for t in s["tests"] if t["arm"] == arm and t["condition"] == cond), None) if s else None
            if t:
                cells[f"{src} n"] = f"{s['n_needed']}/{s['n']}"
                cells[f"{src} raw" if src == "Pilot" else f"{src} raw (w)"] = f"{t['mean_needed']:.3f} vs {t['mean_other']:.3f}"
                cells[f"{src} κ" if src == "Pilot" else f"{src} κ (w)"] = f"p = {pval(t['p_perm_within_gold'])}, Holm {pval(t.get('p_holm'))}"
                tag = ("pilot" if src == "Pilot" else "rTwo") + ("LA" if arm == "xattn_la" else "CE") + ("Swap" if cond == "random_swap" else "Mask")
                num(f"{tag}Needed", f"{t['mean_needed']:.3f}"), num(f"{tag}Other", f"{t['mean_other']:.3f}")
                num(f"{tag}P", pval(t["p_perm_within_gold"])), num(f"{tag}PHolm", pval(t.get("p_holm")))
            else:
                cells.update({f"{src} n": "pending", f"{src} raw (w)" if src != "Pilot" else f"{src} raw": "pending",
                              f"{src} κ (w)" if src != "Pilot" else f"{src} κ": "pending"})
        rows.append({"": lab, **cells})
    s = pilot["gate_a"]["sets"]["needed_both_humans"]
    num("pilotNeeded", str(s["n_needed"])), num("pilotN", str(s["n"]))
    if r2.get("gate_a"):
        num("rTwoNeeded", str(r2["gate_a"]["sets"]["needed_both_humans"]["n_needed"]))
        num("rTwoStrongForm", "yes" if r2["gate_a"]["strong_form_supported"] else "no")
    df = pd.DataFrame(rows)[list(rows[0])]
    df.columns = ["", "Pilot n", "Pilot raw", "Pilot κ", "Round 2 n", "Round 2 raw (w)", "Round 2 κ (w)"]
    write_table(out, "table3_audit", df, tabular(df, "lcccccc"),
                "Human audit. Pilot: 40 items sampled for prediction instability (unweighted). Round 2: stratified "
                "half (60 items), weighted to the private-test class distribution. Gate A rows: mean per-item flip "
                "rate of image-needed items vs the rest (n needed / n rated), two-sided permutation p within gold class "
                "(10,000 permutations), Holm over the four rows.", "tab:audit")


# ---------------------------------------------------------------- Table A1 (appendix)
def table_a1(out):
    scr = pd.read_csv(INPUTS["tau_screen"])
    fin = json.loads(INPUTS["tau_final"].read_text())
    assert all(r["pred_mismatch"] == 0 for r in fin["reproduce_p11"]), "final τ=1.0 must reproduce ca_la"
    rows = []
    for r in scr.itertuples():
        key = {0.75: "075", 1.0: "100"}.get(r.tau)
        s = fin["summary"].get(key) if key else None
        rows.append({"τ": f"{r.tau:.2f}", "OOF macro-F1 (4)": f3(r.macro_f1_4), "OOF fold SD": f3(r.fold_sd),
                     "OOF − τ1.0 [95% CI]": "--" if pd.isna(r.diff_vs_1) else f"{sgn(r.diff_vs_1)} {ci(r.diff_ci_lo, r.diff_ci_hi)}",
                     "Private macro-F1 (4)": f"{s['macro_f1_4'][0]:.3f} ± {s['macro_f1_4'][1]:.3f}" if s else "--",
                     "Private macro-F1 (3)": f"{s['macro_f1_3'][0]:.3f} ± {s['macro_f1_3'][1]:.3f}" if s else "--"})
    d4, d3 = fin["diff_4"], fin["diff_3"]
    num("tauOOFGain", sgn(scr.loc[scr.tau == 0.75, "diff_vs_1"].iloc[0]))
    num("tauPrivDiffFour", sgn(d4["point"])), num("tauPrivDiffFourCI", ci(*d4["ci95"]))
    num("tauPrivDiffThree", sgn(d3["point"])), num("tauPrivDiffThreeCI", ci(*d3["ci95"]))
    df = pd.DataFrame(rows)
    write_table(out, "tableA1_tau", df, tabular(df, "cccccc"),
                f"LA τ. Screen: 3-fold group CV on train, seed 42, out-of-fold predictions (n = {int(scr.n_oof.iloc[0]):,}). "
                f"The rule selected τ = 0.75. Private test: full train, seeds 42/1/2, scored once. Paired difference "
                f"τ0.75 − τ1.0: {sgn(d4['point'])} {ci(*d4['ci95'])} (4-class), {sgn(d3['point'])} {ci(*d3['ci95'])} (3-class). "
                "τ = 1.0 kept.", "tab:tau")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=Path("reports/paper_srw"))
    ap.add_argument("--n-perm", type=int, default=10000)
    a = ap.parse_args()
    for sub in ("tables", "figures"):
        (a.out / sub).mkdir(parents=True, exist_ok=True)
    for k, p in INPUTS.items():
        assert p.exists(), f"missing input {k}: {p}"
    table1(a.out)
    table2(a.out)
    table3(a.out, a.n_perm)
    table_a1(a.out)
    shutil.copyfile(INPUTS["fig1"], a.out / "figures" / "fig_flip_direction.pdf")

    tex = ["% generated by scripts/build_srw_tables.py; do not edit"]
    tex += [f"\\newcommand{{\\{k}}}{{{esc(v)}}}" for k, v in sorted(NUM.items())]
    (a.out / "numbers.tex").write_text("\n".join(tex) + "\n")
    (a.out / "numbers.json").write_text(json.dumps(NUM, indent=1, ensure_ascii=False, sort_keys=True))

    def sha(p):
        return hashlib.sha256(Path(p).read_bytes()).hexdigest()
    pilot_files = sorted(PILOT.glob("0[123]_*_*.csv")) + [PILOT / "coordinator_key.csv"]
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
    manifest = {"built_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"), "git_commit": commit,
                "working_tree_dirty": bool(subprocess.run(["git", "status", "--porcelain"], capture_output=True, text=True).stdout),
                "n_perm": a.n_perm, "round2_available": "round2" in INPUTS,
                "inputs": {str(p): sha(p) for p in list(INPUTS.values()) + pilot_files}}
    (a.out / "MANIFEST.json").write_text(json.dumps(manifest, indent=1))
    print(f"wrote {a.out}: {len(NUM)} numbers, round 2 {'included' if manifest['round2_available'] else 'pending'}")


if __name__ == "__main__":
    main()
